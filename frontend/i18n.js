function getSavedLang() {
  return localStorage.getItem('factify_lang') || 'en';
}

function setSavedLang(lang) {
  localStorage.setItem('factify_lang', lang);
}

window.t = function(key) {
  const lang = getSavedLang();
  return (window.translations[lang] && window.translations[lang][key]) || 
         (window.translations['en'] && window.translations['en'][key]) || 
         key;
};

window.applyTranslations = function() {
  const lang = getSavedLang();
  const dict = window.translations[lang] || window.translations['en'];
  
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      // If element contains HTML icons (like our buttons), preserve the span icon
      const iconMatch = el.innerHTML.match(/<span[^>]*class="[^"]*icon[^"]*"[^>]*>.*?<\/span>/i);
      const rippleMatch = el.innerHTML.match(/<span[^>]*class="[^"]*ripple[^"]*"[^>]*>.*?<\/span>/i);
      const iconOnlyMatch = el.innerHTML.match(/^[^\w]*[^\x00-\x7F]+[^\w]*$/i);
      
      let newHtml = dict[key];
      if (iconMatch) newHtml = iconMatch[0] + ' ' + newHtml;
      if (rippleMatch) newHtml = newHtml + ' ' + rippleMatch[0];
      
      // Keep emojis if they were hardcoded before text (e.g. 📊 Overview)
      // Actually we handled this by separating the text or putting emoji in the translation
      
      el.innerHTML = newHtml;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.placeholder = dict[key];
  });

  // Dispatch event for charts or dynamic components to redraw
  window.dispatchEvent(new Event('languageChanged'));
};

document.addEventListener('DOMContentLoaded', () => {
  const langSwitcher = document.getElementById('lang-switcher');
  if (langSwitcher) {
    langSwitcher.value = getSavedLang();
    langSwitcher.addEventListener('change', (e) => {
      setSavedLang(e.target.value);
      applyTranslations();
    });
  }
  applyTranslations();
});
